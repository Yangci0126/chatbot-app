CREATE TABLE IF NOT EXISTS lorebook_entries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  scope TEXT NOT NULL DEFAULT 'worldview',
  owner_id BIGINT NOT NULL,
  keys TEXT DEFAULT '',
  content TEXT DEFAULT '',
  enabled BOOLEAN DEFAULT TRUE,
  priority INT DEFAULT 100,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE lorebook_entries ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "lorebook_select" ON lorebook_entries;
CREATE POLICY "lorebook_select" ON lorebook_entries FOR SELECT USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "lorebook_insert" ON lorebook_entries;
CREATE POLICY "lorebook_insert" ON lorebook_entries FOR INSERT WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "lorebook_update" ON lorebook_entries;
CREATE POLICY "lorebook_update" ON lorebook_entries FOR UPDATE USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "lorebook_delete" ON lorebook_entries;
CREATE POLICY "lorebook_delete" ON lorebook_entries FOR DELETE USING (auth.uid() = user_id);

CREATE INDEX IF NOT EXISTS idx_lorebook_owner ON lorebook_entries(scope, owner_id);
CREATE INDEX IF NOT EXISTS idx_lorebook_uid ON lorebook_entries(user_id);

ALTER TABLE messages ADD COLUMN IF NOT EXISTS variants JSONB DEFAULT '[]'::jsonb;
ALTER TABLE story_messages ADD COLUMN IF NOT EXISTS variants JSONB DEFAULT '[]'::jsonb;
