);
DROP POLICY IF EXISTS "story_chars_delete" ON story_characters;
CREATE POLICY "story_chars_delete" ON story_characters FOR DELETE USING (
  EXISTS (SELECT 1 FROM stories WHERE id=story_id AND user_id=auth.uid())
