-- ============================================================
-- AI 角色扮演聊天机器人 —— Supabase 完整建表脚本
-- 在 Supabase SQL Editor 中一次性运行本脚本即可完成所有配置
-- ============================================================

-- 1. 删除旧触发器（幂等，可重复运行）
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
DROP FUNCTION IF EXISTS handle_new_user();

-- 2. 世界观表（需最先创建，因为 bots/stories 引用它）
CREATE TABLE IF NOT EXISTS worldviews (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  details TEXT DEFAULT '',
  era TEXT DEFAULT '',
  technology TEXT DEFAULT '',
  world_events TEXT DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. 角色表
CREATE TABLE IF NOT EXISTS bots (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  avatar TEXT DEFAULT '🤖',
  avatar_url TEXT DEFAULT '',
  personality TEXT DEFAULT '',
  backstory TEXT DEFAULT '',
  theme_color TEXT DEFAULT '#6366f1',
  model TEXT DEFAULT 'deepseek-chat',
  worldview_id BIGINT REFERENCES worldviews(id) ON DELETE SET NULL,
  basic_info TEXT DEFAULT '',
  appearance TEXT DEFAULT '',
  background_url TEXT DEFAULT '',
  speaking_style TEXT DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. 单聊消息表
CREATE TABLE IF NOT EXISTS messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  bot_id BIGINT NOT NULL REFERENCES bots(id) ON DELETE CASCADE,
  role TEXT NOT NULL CHECK (role IN ('user', 'assistant')),
  content TEXT NOT NULL,
  variants JSONB DEFAULT '[]'::jsonb,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. 用户设置表（存储 LLM / 生图 API 配置）
CREATE TABLE IF NOT EXISTS user_settings (
  user_id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  api_key TEXT DEFAULT '',
  api_base_url TEXT DEFAULT 'https://api.deepseek.com/v1',
  default_model TEXT DEFAULT 'deepseek-chat',
  display_name TEXT DEFAULT '',
  avatar_url TEXT DEFAULT '',
  gender TEXT DEFAULT '',
  image_api_key TEXT DEFAULT '',
  image_api_base_url TEXT DEFAULT '',
  image_model TEXT DEFAULT '',
  image_size TEXT DEFAULT '1024x1024',
  image_quality TEXT DEFAULT 'standard',
  image_style TEXT DEFAULT '',
  speaking_style TEXT DEFAULT '',
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. 剧本表
CREATE TABLE IF NOT EXISTS stories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  background TEXT DEFAULT '',
  worldview_id BIGINT REFERENCES worldviews(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 7. 剧本角色关联表
CREATE TABLE IF NOT EXISTS story_characters (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  story_id BIGINT NOT NULL REFERENCES stories(id) ON DELETE CASCADE,
  bot_id BIGINT NOT NULL REFERENCES bots(id) ON DELETE CASCADE
);

-- 8. 剧本消息表
CREATE TABLE IF NOT EXISTS story_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  story_id BIGINT NOT NULL REFERENCES stories(id) ON DELETE CASCADE,
  role TEXT NOT NULL CHECK (role IN ('user', 'assistant')),
  content TEXT NOT NULL,
  variants JSONB DEFAULT '[]'::jsonb,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 9. 世界书（关键词触发的设定条目）
CREATE TABLE IF NOT EXISTS lorebook_entries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  scope TEXT NOT NULL DEFAULT 'worldview',
  owner_id BIGINT NOT NULL,
  keys TEXT DEFAULT '',
  content TEXT DEFAULT '',
  enabled BOOLEAN DEFAULT TRUE,
  priority INT DEFAULT 100,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 10. 老版本升级兼容：为已存在的表补齐新增字段（幂等）
ALTER TABLE worldviews ADD COLUMN IF NOT EXISTS details TEXT DEFAULT '';
ALTER TABLE messages ADD COLUMN IF NOT EXISTS variants JSONB DEFAULT '[]'::jsonb;
ALTER TABLE story_messages ADD COLUMN IF NOT EXISTS variants JSONB DEFAULT '[]'::jsonb;
ALTER TABLE bots ADD COLUMN IF NOT EXISTS speaking_style TEXT DEFAULT '';
ALTER TABLE bots ADD COLUMN IF NOT EXISTS background_url TEXT DEFAULT '';
ALTER TABLE bots ADD COLUMN IF NOT EXISTS avatar_url TEXT DEFAULT '';
ALTER TABLE bots ADD COLUMN IF NOT EXISTS basic_info TEXT DEFAULT '';
ALTER TABLE bots ADD COLUMN IF NOT EXISTS appearance TEXT DEFAULT '';
ALTER TABLE user_settings ADD COLUMN IF NOT EXISTS speaking_style TEXT DEFAULT '';

-- 11. 把旧版世界观的「时代/科技/大事件」迁移到 details（仅迁移 details 为空的行）
UPDATE worldviews
SET details = CONCAT_WS(chr(10), NULLIF(era,''), NULLIF(technology,''), NULLIF(world_events,''))
WHERE COALESCE(details,'') = ''
  AND (COALESCE(era,'') <> '' OR COALESCE(technology,'') <> '' OR COALESCE(world_events,'') <> '');

-- 12. 更新时间戳函数
CREATE OR REPLACE FUNCTION update_timestamp()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS bots_updated_at ON bots;
CREATE TRIGGER bots_updated_at BEFORE UPDATE ON bots
  FOR EACH ROW EXECUTE FUNCTION update_timestamp();

DROP TRIGGER IF EXISTS settings_updated_at ON user_settings;
CREATE TRIGGER settings_updated_at BEFORE UPDATE ON user_settings
  FOR EACH ROW EXECUTE FUNCTION update_timestamp();

